"use client";

import { useEffect, useState } from "react";
import { Banner } from "@via-ds/components/banner";
import { CodeBlock, CodeSnippet } from "@via-ds/components/code-block";
import { Text } from "@via-ds/components/typography";
import { useSelector } from "react-redux";
import { selectDisplayedEvent, selectSelectedUser } from "@/redux/slices/GlobalSlice";
import { fetchOrderLoyaltyHistory } from "@/lib/api";
import { docToJSON } from "@/lib/helper";
import modalStyles from "./EventContent.module.css";
import SyncModal from "../modals/SyncModal/SyncModal";

const RecordLoyaltyEventContent = ({ embedded = false }) => {
  const activeEvent = useSelector(selectDisplayedEvent);
  const persona = useSelector(selectSelectedUser);
  const orderId = activeEvent?.order?.orderId;
  const customerId = activeEvent?.order?.customerId ?? persona?.customerId;
  const [entries, setEntries] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    let cancelled = false;
    setEntries([]);
    setError(null);

    if (!orderId || !customerId) {
      setLoading(false);
      return;
    }

    setLoading(true);
    fetchOrderLoyaltyHistory({ orderId, customerId })
      .then((data) => {
        if (!cancelled) setEntries(data);
      })
      .catch((err) => {
        if (!cancelled) setError(err.message);
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });

    return () => {
      cancelled = true;
    };
  }, [orderId, customerId]);

  const tabs = [
    {
      key: "doc",
      label: "The loyalty ledger",
      render: () => (
        <div className={modalStyles.content}>
          <section>
            <h3>Build an Append-Only Loyalty Ledger</h3>
            <p>
              Retailers need to know <strong>how that balance was earned,
              redeemed, or changed over time.</strong> Each loyalty event
              generated by an order, such as coins earned, coins redeemed, or
              a tier change, is appended to the customer's
              {" "}<strong>loyalty ledger.</strong>
            </p>
            <p>
              Every loyalty event is added as a new document rather than
              modifying an existing historical record.
            </p>
          </section>
          <section>
            <h4>One history, multiple business uses</h4>
            <p>This gives retailers a durable record that can support:</p>
            <ul className={modalStyles.fields}>
              <li><strong>Customer self-service:</strong> &ldquo;My Coins&rdquo; history</li>
              <li><strong>Customer service:</strong> investigating loyalty disputes</li>
              <li><strong>Operations:</strong> understanding how a customer's balance changed</li>
              <li><strong>Audit:</strong> tracing loyalty activity back to an order and transaction</li>
            </ul>
            <p>
              This creates a durable history that can support customer
              experiences, operational teams, and future analytics.
            </p>
          </section>
          <Banner className={modalStyles.banner} variant="info">
            <div>
              <p><strong>Current loyalty &rarr; Customer profile</strong></p>
              <p><strong>Historical loyalty events &rarr; Loyalty ledger</strong></p>
            </div>
          </Banner>
        </div>
      ),
    },
    {
      key: "model",
      label: "Document Model",
      render: () => {
        return (
          <div className={modalStyles.content}>
            <section>
              <h3>A document for every loyalty event</h3>
              <p>
                Every loyalty event is added as a new document rather than
                modifying an existing historical record.
              </p>
              <div className={modalStyles.documentHead}>
                <h4>Loyalty history records</h4>
                <span className={modalStyles.badge}>Stored ledger entries</span>
              </div>
              {!orderId || !customerId ? (
                <p>No order is available.</p>
              ) : loading ? (
                <p role="status">Loading loyalty history...</p>
              ) : error ? (
                <p role="alert">Couldn't load loyalty history: {error}</p>
              ) : !entries.length ? (
                <p>No loyalty history entries were found for this order.</p>
              ) : (
                <CodeBlock language="json">
                  <CodeSnippet>{docToJSON(entries)}</CodeSnippet>
                </CodeBlock>
              )}
            </section>
            <section>
              <h3>Loyalty Model Can Evolve with Your Business</h3>
              <p>Loyalty programs rarely stay static. Today, a retailer may have events for:</p>
              <ul className={modalStyles.fields}>
                <li><code>earn</code></li>
                <li><code>redeem</code></li>
                <li><code>tier-change</code></li>
              </ul>
              <p>Tomorrow, the program may introduce:</p>
              <ul className={modalStyles.fields}>
                <li><code>expiry</code></li>
                <li><code>bonus</code></li>
                <li><code>adjustment</code></li>
                <li><code>referral</code></li>
                <li><code>campaign-bonus</code></li>
              </ul>
            </section>
            <Banner className={modalStyles.banner} variant="info">
              <div>
                <Text as="strong">Different events, one collection</Text>
                <p>
                  This is where MongoDB's <strong>polymorphic document
                  model</strong> becomes particularly useful. This flexibility
                  allows loyalty events to have different attributes while still
                  living in the same collection, and easily evolve the schema
                  as your business needs change.
                </p>
              </div>
            </Banner>
          </div>
        );
      },
    },
    {
      key: "intelligence",
      label: "Future Intelligence",
      render: () => (
        <div className={modalStyles.content}>
          <section>
            <h3>Turn Historical Data Into Future Intelligence</h3>
            <p>The value of the ledger doesn't stop at auditability.</p>
            <p>
              Once loyalty events accumulate, they become a source of
              <strong> behavioral context.</strong>
            </p>
          </section>
          <section>
            <h4>Patterns retailers can explore</h4>
            <p>Retailers can analyze patterns such as:</p>
            <ul className={modalStyles.fields}>
              <li>When customers are most likely to redeem rewards</li>
              <li>Average coins redeemed per transaction</li>
              <li>Which product categories generate the most redemptions</li>
              <li>How redemption behavior changes by season</li>
              <li>How promotions influence earning and redemption behavior</li>
            </ul>
          </section>
          <section>
            <h4>Context for future AI applications</h4>
            <p>
              This history can also become context for future AI applications,
              such as an agent that helps identify loyalty opportunities or
              understand a customer's reward behavior.
            </p>
          </section>
          <Banner className={modalStyles.banner} variant="info">
            <strong>Today's loyalty history can become tomorrow's customer intelligence.</strong>
          </Banner>
        </div>
      ),
    },
  ];

  return <SyncModal title="Save the loyalty history" tabs={tabs} embedded={embedded} />;
};

export default RecordLoyaltyEventContent;